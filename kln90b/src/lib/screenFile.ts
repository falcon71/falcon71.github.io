// The generated screen file (screen.txt). The generator writes it and the Astro site reads it, so this module has no
// imports.

export type CellAttr = '.' | 'I' | 'B' | 'F';      // normal, inverse, flashing text, flashing inverse
export type Show = 'left' | 'right' | 'both';
/** split: halves in columns 0-10 and 12-22, column 11 the middle line; super-nav-5: the left column over a full-page map */
export type Layout = 'split' | 'full' | 'super-nav-5';
/** The map of the left half, the right half or the full page (Super NAV 5) */
export type MapSide = 'L' | 'R' | 'F';

/** Cells `from` to `to` (exclusive) of one screen row. */
export interface FieldPart {
	row: number;    // screen row 0-6
	from: number;   // column 0-22
	to: number;     // exclusive, 1-23
}

export interface ScreenCapture {
	kln90b: string;            // 40-char commit
	title: string;
	show: Show;
	layout: Layout;
	status: boolean;           // false only for a full page without status line (the welcome page) and Super NAV 5
	text: string[];            // 7 rows of 23 characters
	mask: CellAttr[][];        // 7 rows of 23
	fields: Map<string, FieldPart[]>;   // in order of the description
	mapFields: Map<string, MapSide>;  // field id to the map side it is drawn on, in order of the description
	maps: MapSide[];           // sides with a map-<side>.svg
}

const ROWS = 7;
const COLUMNS = 23;
const HEADER = '# Generated by "npm run screens" from screen.ts in this folder. Do not edit.';
const ATTRS = '.IBF';
const SHOWS: Show[] = ['left', 'right', 'both'];
const LAYOUTS: Layout[] = ['split', 'full', 'super-nav-5'];
const SIDES: MapSide[] = ['L', 'R', 'F'];
const COMMIT = /^[0-9a-f]{40}$/;

/** The characters of a row. The font maps its glyphs onto Greek and Cyrillic code points, so these are plain strings. */
function chars(row: string): string[] {
	return Array.from(row);
}

function checkRow(kind: string, row: number, cells: string[]): void {
	if (cells.length !== COLUMNS) throw new Error(`${kind} row ${row} has ${cells.length} characters instead of ${COLUMNS}`);
}

function checkPart(id: string, part: FieldPart): void {
	const ok = Number.isInteger(part.row) && Number.isInteger(part.from) && Number.isInteger(part.to) &&
		part.row >= 0 && part.row < ROWS && part.from >= 0 && part.from < part.to && part.to <= COLUMNS;
	if (!ok) {
		throw new Error(`field ${id} has the part row ${part.row} from ${part.from} to ${part.to}, ` +
			`which is outside the ${ROWS} rows of ${COLUMNS} columns`);
	}
}

function checkCapture(c: ScreenCapture): void {
	if (!COMMIT.test(c.kln90b)) throw new Error(`kln90b "${c.kln90b}" is not a 40-character commit`);
	if (c.title.trim() === '' || /[\r\n]/.test(c.title)) throw new Error('title must be one non-empty line');
	if (!SHOWS.includes(c.show)) throw new Error(`show "${c.show}" is not left, right or both`);
	if (!LAYOUTS.includes(c.layout)) throw new Error(`layout "${c.layout}" is not split, full or super-nav-5`);
	const page = pageProblem(c.layout, c.show, c.status);
	if (page !== null) throw new Error(page);
	if (c.text.length !== ROWS) throw new Error(`text has ${c.text.length} rows instead of ${ROWS}`);
	if (c.mask.length !== ROWS) throw new Error(`mask has ${c.mask.length} rows instead of ${ROWS}`);
	c.text.forEach((row, i) => {
		checkRow('text', i, chars(row));
		if (/[\r\n]/.test(row)) throw new Error(`text row ${i} contains a line break`);
	});
	c.mask.forEach((row, i) => {
		checkRow('mask', i, row);
		for (const attr of row) {
			if (attr.length !== 1 || !ATTRS.includes(attr)) throw new Error(`mask row ${i} has the unknown attribute "${attr}"`);
		}
	});
	for (const [id, parts] of c.fields) {
		if (!/^\S+$/.test(id)) throw new Error(`field id "${id}" must be one word without blanks`);
		if (parts.length === 0) throw new Error(`field ${id} has no parts`);
		parts.forEach(part => checkPart(id, part));
	}
	for (const side of c.maps) {
		if (!SIDES.includes(side)) throw new Error(`map "${side}" is not L, R or F`);
		const problem = mapProblem(side, c.layout);
		if (problem !== null) throw new Error(problem);
	}
	if (new Set(c.maps).size !== c.maps.length) throw new Error(`map ${c.maps.join(', ')} lists a side twice`);
	for (const [id, side] of c.mapFields) {
		if (!/^\S+$/.test(id)) throw new Error(`map field id "${id}" must be one word without blanks`);
		const problem = mapFieldProblem(id, side, c.fields, c.maps);
		if (problem !== null) throw new Error(problem);
	}
}

/**
 * What is wrong with the show and the status line of a layout, or null: Super NAV 5 is the whole screen, without status
 * line.
 */
function pageProblem(layout: Layout, show: Show, status: boolean): string | null {
	if (layout !== 'super-nav-5') return null;
	if (show !== 'both') return `layout super-nav-5 needs show both, not ${show}`;
	if (status) return 'layout super-nav-5 has no status line, so it needs status no';
	return null;
}

/** What is wrong with a map of a layout, or null: the half pages have the maps L and R, Super NAV 5 the map F. */
function mapProblem(side: MapSide, layout: Layout): string | null {
	if ((side === 'F') === (layout === 'super-nav-5')) return null;
	return `map ${side} does not exist on layout ${layout}`;
}

/** What is wrong with a map field, given all text fields and maps of the capture, or null. */
function mapFieldProblem(id: string, side: string, fields: Map<string, FieldPart[]>, maps: string[]): string | null {
	if (!SIDES.includes(side as MapSide)) return `map field ${id} names the side "${side}", which is not L, R or F`;
	if (fields.has(id)) return `map field ${id} is also a text field`;
	if (!maps.includes(side)) return `map field ${id} is drawn on map ${side}, which has no "map ${side}" line`;
	return null;
}

export function serializeScreenFile(c: ScreenCapture): string {
	checkCapture(c);
	const lines = [
		HEADER,
		`kln90b ${c.kln90b}`,
		`title ${c.title}`,
		`show ${c.show}`,
		`layout ${c.layout}`,
		`status ${c.status ? 'yes' : 'no'}`,
		'text',
		...c.text.map(row => `|${row}|`),
		'mask',
		...c.mask.map(row => `|${row.join('')}|`),
	];
	for (const [id, parts] of c.fields) {
		for (const part of parts) lines.push(`field ${id} ${part.row} ${part.from} ${part.to}`);
	}
	for (const [id, side] of c.mapFields) lines.push(`mapfield ${id} ${side}`);
	for (const side of c.maps) lines.push(`map ${side}`);
	return lines.join('\n') + '\n';
}

/** Reads the lines of the file one by one; every error names the line it is about. */
class Reader {
	private next = 0;

	constructor(private readonly lines: string[]) {
	}

	/** Throws about the line read last (numbered from 1). */
	fail(message: string): never {
		this.failAt(this.next, message);
	}

	/** Throws about a line read earlier (numbered from 1). */
	failAt(line: number, message: string): never {
		throw new Error(`screen file line ${line}: ${message}`);
	}

	/** The number of the line read last (from 1). */
	get line(): number {
		return this.next;
	}

	/** The next line that is neither blank nor a comment, or null at the end. Only used outside the blocks. */
	nextItem(): string | null {
		for (; ;) {
			const line = this.nextRaw();
			if (line === null) return null;
			if (line.trim() === '' || line.startsWith('#')) continue;
			return line;
		}
	}

	/** The next line, whatever it is, or null at the end. */
	nextRaw(): string | null {
		if (this.next >= this.lines.length) return null;
		return this.lines[this.next++];
	}

	/** The value of a line `<key> <value>`. */
	value(key: string): string {
		const line = this.nextItem();
		if (line === null) this.fail(`expected "${key}" but the file ends`);
		const prefix = key + ' ';
		if (!line.startsWith(prefix) || line.slice(prefix.length).trim() === '') {
			this.fail(`expected "${key} <value>" but found "${line}"`);
		}
		return line.slice(prefix.length);
	}

	/** The 7 rows between `|` of a block. */
	block(kind: 'text' | 'mask'): string[][] {
		const line = this.nextItem();
		if (line !== kind) this.fail(`expected "${kind}" but found ${line === null ? 'the end of the file' : `"${line}"`}`);
		const rows: string[][] = [];
		for (let row = 0; row < ROWS; row++) {
			const raw = this.nextRaw();
			if (raw === null) this.fail(`${kind} row ${row} is missing, the file ends`);
			if (raw.length < 2 || !raw.startsWith('|') || !raw.endsWith('|')) {
				this.fail(`${kind} row ${row} must be between | characters but is "${raw}"`);
			}
			const cells = chars(raw.slice(1, -1));
			if (cells.length !== COLUMNS) {
				this.fail(`${kind} row ${row} has ${cells.length} characters instead of ${COLUMNS}`);
			}
			rows.push(cells);
		}
		return rows;
	}
}

function oneOf<T extends string>(r: Reader, key: string, allowed: readonly T[]): T {
	const value = r.value(key);
	if (!allowed.includes(value as T)) r.fail(`${key} must be ${allowed.join(', ')} but is "${value}"`);
	return value as T;
}

export function parseScreenFile(text: string): ScreenCapture {
	const r = new Reader(text.split(/\r?\n/));

	const kln90b = r.value('kln90b');
	if (!COMMIT.test(kln90b)) r.fail(`kln90b must be a 40-character commit but is "${kln90b}"`);
	const title = r.value('title');
	const show = oneOf(r, 'show', SHOWS);
	const layout = oneOf(r, 'layout', LAYOUTS);
	// The show is checked on the layout line, the line that makes it wrong
	const shown = pageProblem(layout, show, false);
	if (shown !== null) r.fail(shown);
	const status = oneOf(r, 'status', ['yes', 'no'] as const) === 'yes';
	const page = pageProblem(layout, show, status);
	if (page !== null) r.fail(page);

	const rows = r.block('text');
	const mask = r.block('mask').map((cells, row) => cells.map(cell => {
		if (!ATTRS.includes(cell)) r.fail(`mask row ${row} has the unknown attribute "${cell}"`);
		return cell as CellAttr;
	}));

	const fields = new Map<string, FieldPart[]>();
	const mapFields = new Map<string, MapSide>();
	const mapFieldLines = new Map<string, number>();
	const maps: MapSide[] = [];
	for (let line = r.nextItem(); line !== null; line = r.nextItem()) {
		const words = line.trim().split(/\s+/);
		if (words[0] === 'field') {
			if (words.length !== 5) r.fail(`expected "field <id> <row> <from> <to>" but found "${line}"`);
			const [, id, ...numbers] = words;
			if (!numbers.every(n => /^-?\d+$/.test(n))) r.fail(`field ${id} needs whole numbers but found "${line}"`);
			const [row, from, to] = numbers.map(Number);
			const part = {row, from, to};
			try {
				checkPart(id, part);
			} catch (e) {
				r.fail((e as Error).message);
			}
			const parts = fields.get(id);
			if (parts) parts.push(part); else fields.set(id, [part]);
		} else if (words[0] === 'mapfield') {
			const [, id, side] = words;
			if (words.length !== 3 || !SIDES.includes(side as MapSide)) r.fail(`expected "mapfield <id> <L, R or F>" but found "${line}"`);
			if (mapFields.has(id)) r.fail(`map field ${id} appears twice`);
			mapFields.set(id, side as MapSide);
			mapFieldLines.set(id, r.line);
		} else if (words[0] === 'map') {
			const side = words[1];
			if (words.length !== 2 || !SIDES.includes(side as MapSide)) r.fail(`expected "map L", "map R" or "map F" but found "${line}"`);
			if (maps.includes(side as MapSide)) r.fail(`map ${side} appears twice`);
			const problem = mapProblem(side as MapSide, layout);
			if (problem !== null) r.fail(problem);
			maps.push(side as MapSide);
		} else {
			r.fail(`unknown line "${line}"`);
		}
	}

	// The text fields and maps a map field is checked against may come after it
	for (const [id, side] of mapFields) {
		const problem = mapFieldProblem(id, side, fields, maps);
		if (problem !== null) r.failAt(mapFieldLines.get(id)!, problem);
	}

	return {kln90b, title, show, layout, status, text: rows.map(cells => cells.join('')), mask, fields, mapFields, maps};
}

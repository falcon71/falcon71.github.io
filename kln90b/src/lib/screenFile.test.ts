import {describe, expect, it} from 'vitest';
import {parseScreenFile, serializeScreenFile, type CellAttr, type ScreenCapture} from './screenFile';

function capture(): ScreenCapture {
	const text = [
		'APT 1       ' + 'KSEA'.padEnd(10),
		'SEATTLE-TACOMA INTL   ',
		'  η 12° N 47° 26.9  ',
		'                       ',
		'trailing blanks kept   ',
		'ident 0123456789 ABCDE ',
		'APT 1                  ',
	].map(row => row.padEnd(23).slice(0, 23));
	const mask: CellAttr[][] = text.map(() => Array.from({length: 23}, () => '.' as CellAttr));
	mask[0][0] = 'I';
	mask[0][1] = 'B';
	mask[1][22] = 'F';
	return {
		title: 'APT 1 page',
		show: 'right',
		layout: 'split',
		status: true,
		text,
		mask,
		fields: new Map([
			['ident', [{row: 0, from: 15, to: 19}]],
			['name', [{row: 1, from: 12, to: 23}, {row: 2, from: 12, to: 20}]],
		]),
		mapFields: new Map([['aircraft', 'L'], ['leg', 'L']]),
		maps: ['L'],
	};
}

/** The serialized capture with one line replaced (lines are 0-based). */
function withLine(index: number, line: string): string {
	const lines = serializeScreenFile(capture()).split('\n');
	lines[index] = line;
	return lines.join('\n');
}

describe('screen file', () => {
	it('round-trips a capture', () => {
		const c = capture();
		expect(parseScreenFile(serializeScreenFile(c))).toEqual(c);
	});

	it('writes the documented layout', () => {
		const lines = serializeScreenFile(capture()).split('\n');
		expect(lines[0]).toBe('# Generated by "npm run screens" from screen.ts in this folder. Do not edit.');
		expect(lines.slice(1, 7)).toEqual([
			'title APT 1 page', 'show right', 'layout split', 'status yes', 'text',
			'|APT 1       KSEA       |',
		]);
		expect(lines.slice(-7)).toEqual([
			'field ident 0 15 19', 'field name 1 12 23', 'field name 2 12 20', 'mapfield aircraft L', 'mapfield leg L', 'map L', '',
		]);
	});

	it('groups the parts of a field and keeps the order of the fields', () => {
		const c = capture();
		c.fields = new Map([
			['zeta', [{row: 3, from: 0, to: 2}]],
			['alpha', [{row: 4, from: 1, to: 3}, {row: 5, from: 4, to: 6}]],
		]);
		const parsed = parseScreenFile(serializeScreenFile(c));
		expect([...parsed.fields.keys()]).toEqual(['zeta', 'alpha']);
		expect(parsed.fields.get('alpha')).toEqual([{row: 4, from: 1, to: 3}, {row: 5, from: 4, to: 6}]);
	});

	it('round-trips a full page without status line and both maps', () => {
		const c = capture();
		c.layout = 'full';
		c.status = false;
		c.show = 'both';
		c.maps = ['L', 'R'];
		c.fields = new Map();
		c.mapFields = new Map([['runway', 'R'], ['aircraft', 'L']]);
		const parsed = parseScreenFile(serializeScreenFile(c));
		expect(parsed).toEqual(c);
		expect([...parsed.mapFields.keys()]).toEqual(['runway', 'aircraft']);
	});

	it('round-trips Super NAV 5 with its full-page map', () => {
		const c = capture();
		c.layout = 'super-nav-5';
		c.status = false;
		c.show = 'both';
		c.maps = ['F'];
		c.fields = new Map([['distance', [{row: 0, from: 0, to: 4}]]]);
		c.mapFields = new Map([['aircraft', 'F']]);
		const text = serializeScreenFile(c);
		expect(text).toContain('\nlayout super-nav-5\n');
		expect(text).toContain('\nmapfield aircraft F\nmap F\n');
		expect(parseScreenFile(text)).toEqual(c);
	});

	it('keeps the full-page map to Super NAV 5 and the half-page maps to the split layout', () => {
		const snav5 = capture();
		snav5.layout = 'super-nav-5';
		snav5.status = false;
		snav5.show = 'both';
		snav5.fields = new Map();
		const text = serializeScreenFile({...snav5, maps: ['F'], mapFields: new Map([['aircraft', 'F']])});
		expect(() => serializeScreenFile(snav5)).toThrow(/map L.*super-nav-5/);
		expect(() => parseScreenFile(text.replace('map F', 'map F\nmap L'))).toThrow(/line 24: .*map L.*super-nav-5/);
		const split = capture();
		expect(() => serializeScreenFile({...split, maps: ['F'], mapFields: new Map()})).toThrow(/map F.*split/);
		expect(() => parseScreenFile(serializeScreenFile(split).replace('map L', 'map L\nmap F')))
			.toThrow(/line 28: .*map F.*split/);
		expect(() => serializeScreenFile({...snav5, maps: [], mapFields: new Map(), show: 'left'})).toThrow(/super-nav-5.*show both/);
		expect(() => serializeScreenFile({...snav5, maps: [], mapFields: new Map(), status: true})).toThrow(/super-nav-5.*status/);
		expect(() => parseScreenFile(text.replace('show both', 'show left'))).toThrow(/line 4: .*super-nav-5.*show both/);
		expect(() => parseScreenFile(text.replace('status no', 'status yes'))).toThrow(/line 5: .*super-nav-5.*status/);
	});

	it('re-serializes every committed screen file to the same text', () => {
		const files = import.meta.glob<string>('../../screens/*/screen.txt', {query: '?raw', import: 'default', eager: true});
		// The glob finds them: a screen with a map is among them
		expect(Object.keys(files)).toContain('../../screens/nav-5-ksea/screen.txt');
		for (const [name, text] of Object.entries(files)) {
			expect(serializeScreenFile(parseScreenFile(text)), name).toBe(text);
		}
	});

	it('round-trips a capture without map fields', () => {
		const c = capture();
		c.mapFields = new Map();
		expect(serializeScreenFile(c)).not.toContain('mapfield');
		expect(parseScreenFile(serializeScreenFile(c))).toEqual(c);
	});

	it('parses CRLF', () => {
		const text = serializeScreenFile(capture());
		expect(parseScreenFile(text.replace(/\n/g, '\r\n'))).toEqual(capture());
	});

	it('keeps the trailing blanks of a row', () => {
		const parsed = parseScreenFile(serializeScreenFile(capture()));
		expect(parsed.text[4]).toBe('trailing blanks kept   ');
		expect(parsed.text[4]).toHaveLength(23);
	});

	it('ignores comments and blank lines outside the blocks', () => {
		const text = '\n# a note\n' + serializeScreenFile(capture()).replace('show right', '\n# another\nshow right\n');
		expect(parseScreenFile(text)).toEqual(capture());
	});

	it('rejects a short row', () => {
		const lines = serializeScreenFile(capture()).split('\n');
		const first = lines.indexOf('text') + 1;
		expect(() => parseScreenFile(withLine(first + 3, '|' + 'x'.repeat(22) + '|'))).toThrow('text row 3');
	});

	it('rejects a long row and a row without delimiters', () => {
		const first = serializeScreenFile(capture()).split('\n').indexOf('text') + 1;
		expect(() => parseScreenFile(withLine(first, '|' + 'x'.repeat(24) + '|'))).toThrow('text row 0');
		expect(() => parseScreenFile(withLine(first + 1, 'x'.repeat(23)))).toThrow('text row 1');
	});

	it('rejects an unknown attribute', () => {
		const first = serializeScreenFile(capture()).split('\n').indexOf('mask') + 1;
		expect(() => parseScreenFile(withLine(first + 2, '|' + '.'.repeat(22) + 'X|'))).toThrow('mask row 2');
	});

	it('rejects a missing row', () => {
		const lines = serializeScreenFile(capture()).split('\n');
		lines.splice(lines.indexOf('mask') - 1, 1);
		expect(() => parseScreenFile(lines.join('\n'))).toThrow('text row 6');
	});

	it('rejects a field outside the screen', () => {
		const text = serializeScreenFile(capture());
		for (const bad of ['field a 7 0 1', 'field a -1 0 1', 'field a 0 -1 1', 'field a 0 0 24', 'field a 0 5 5', 'field a 0 6 5',
			'field a 0.5 0 1', 'field a 0 0', 'field a 0 0 1 2']) {
			expect(() => parseScreenFile(text.replace('map L', bad)), bad).toThrow(/field/);
		}
	});

	it('rejects malformed header lines, naming the line', () => {
		expect(() => parseScreenFile(withLine(1, 'title'))).toThrow('line 2');
		expect(() => parseScreenFile(withLine(2, 'show middle'))).toThrow('line 3');
		expect(() => parseScreenFile(withLine(3, 'layout wide'))).toThrow('line 4');
		expect(() => parseScreenFile(withLine(4, 'status maybe'))).toThrow('line 5');
	});

	it('refuses a file of an older generator that still has the kln90b line, and says to regenerate', () => {
		const lines = serializeScreenFile(capture()).split('\n');
		lines.splice(1, 0, 'kln90b 3d371f34a68144c80f8e7035490d8f0391b0eb45');
		expect(() => parseScreenFile(lines.join('\n'))).toThrow(/line 2: .*kln90b.*npm run screens/);
	});

	it('writes no kln90b line', () => {
		expect(serializeScreenFile(capture())).not.toMatch(/^kln90b/m);
	});

	it('rejects an unknown line and a repeated map side', () => {
		const text = serializeScreenFile(capture());
		expect(() => parseScreenFile(text.replace('map L', 'color red'))).toThrow('color red');
		expect(() => parseScreenFile(text.replace('map L', 'map L\nmap L'))).toThrow('map');
		expect(() => parseScreenFile(text.replace('map L', 'map X'))).toThrow('map X');
	});

	it('rejects a map field without its map, one that is also a text field, a repeated one and a malformed one', () => {
		const text = serializeScreenFile(capture());
		expect(() => parseScreenFile(text.replace('mapfield leg L', 'mapfield leg R'))).toThrow(/line 26: .*leg.*map R/);
		expect(() => parseScreenFile(text.replace('mapfield leg L', 'mapfield name L'))).toThrow(/line 26: .*name.*text field/);
		expect(() => parseScreenFile(text.replace('mapfield leg L', 'mapfield aircraft L'))).toThrow(/line 26: .*aircraft.*twice/);
		expect(() => parseScreenFile(text.replace('mapfield leg L', 'mapfield aircraft R\nmap R'))).toThrow(/aircraft.*twice/);
		for (const bad of ['mapfield leg', 'mapfield leg X', 'mapfield leg L R']) {
			expect(() => parseScreenFile(text.replace('mapfield leg L', bad)), bad).toThrow(/line 26: .*mapfield/);
		}
	});

	it('refuses to write a capture that would not parse', () => {
		const c = capture();
		c.text[2] = 'short';
		expect(() => serializeScreenFile(c)).toThrow('text row 2');
		const d = capture();
		d.title = 'two\nlines';
		expect(() => serializeScreenFile(d)).toThrow('title');
		const e = capture();
		e.maps = ['L', 'L'];
		expect(() => serializeScreenFile(e)).toThrow('map L');
		const f = capture();
		f.mapFields.set('runway', 'R');
		expect(() => serializeScreenFile(f)).toThrow(/runway.*map R/);
		const g = capture();
		g.mapFields.set('name', 'L');
		expect(() => serializeScreenFile(g)).toThrow(/name.*text field/);
		const h = capture();
		h.mapFields.set('two words', 'L');
		expect(() => serializeScreenFile(h)).toThrow(/two words/);
	});
});
